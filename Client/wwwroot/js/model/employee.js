class Employee {
    constructor(id, firstName, lastName, gender, email, phone, birthDate, image, managerId) {
        this.id = id;
        this.firstName = firstName;
        this.lastName = lastName;
        this.phone = phone;
        this.birthDate = birthDate;
        this.email = email;
        this.gender = gender;
        this.image = image;
        this.managerId = managerId;
    }

}

